const dictionaries: Record<Locale, Record<MessageKey, string>> = { pt, en };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[locale][key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

const LocaleContext = createContext<Locale>('pt');

export function LocaleProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = locale === 'pt' ? 'pt-BR' : 'en';
  }, [locale]);
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

// `t` é estável por idioma: pode entrar em dependências de useCallback/useEffect sem gerar loop.
export function useI18n() {
  const locale = useContext(LocaleContext);
  return useMemo(() => ({ locale, t: (key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars) }), [locale]);
}

export function browserLocale(): Locale {
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}
